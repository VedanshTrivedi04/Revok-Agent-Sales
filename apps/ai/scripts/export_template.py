"""Write the ML data contract: docs/ml-data-contract.md and an empty CSV template per task.

    uv run python scripts/export_template.py

Give the CSV template to whoever exports your real renewals. Every column is documented; optional columns
may be left out (they are treated as missing, which the models were trained to handle).
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import pandas as pd  # noqa: E402

from revops_ai.ml.specs import TASKS  # noqa: E402


def main() -> None:
    out_dir = ROOT / "data" / "templates"
    out_dir.mkdir(parents=True, exist_ok=True)
    lines = [
        "# ML data contract (churn + expansion)", "",
        "Generated by `scripts/export_template.py` from `revops_ai/ml/specs.py`. To train on REAL data, export one CSV per",
        "task with these columns and run `uv run python scripts/train_model.py --task <churn|expansion> --csv <file>`.",
        "Use `--validate-only` first: it prints errors (blocking) and warnings (informational).", "",
        "**One row = one renewal event.** All features are measured at a snapshot **90 days before the renewal date**",
        "(never use data from after the snapshot: it would leak the answer). The label is observed afterwards.", "",
        "Rules: at least 500 rows, >= 50 positives and >= 50 negatives; dates should span > 1 year (validation is time-based:",
        "oldest 60% train, next 12% early-stopping, 14% calibration, newest 14% test). Unknown categories become missing.", "",
    ]  # fmt: skip
    for name, spec in TASKS.items():
        lines += [f"## Task `{name}` - {spec.title}", "", f"Target `{spec.target}`: {spec.target_desc}.", "", "| Column | Type | Required | Plausible range / values | Meaning |", "|---|---|---|---|---|"]  # fmt: skip
        lines += [f"| `{spec.id_col}` | text | yes | - | Account id (repeats across renewals) |", f"| `{spec.org_col}` | text | no | - | Customer-org / tenant id (enables the unseen-org evaluation) |", f"| `{spec.date_col}` | date | yes | - | Renewal date |", f"| `{spec.target}` | 0/1 | yes | 0 or 1 | Label |"]  # fmt: skip
        for c in spec.features:
            rng = ", ".join(c.categories) if c.categories else (f"{c.lo if c.lo is not None else ''}..{c.hi if c.hi is not None else ''}" if (c.lo is not None or c.hi is not None) else "")  # fmt: skip
            lines.append(
                f"| `{c.name}` | {c.kind} | {'yes' if c.required else 'no'} | {rng} | {c.desc} |"
            )
        lines += [""] + [f"- {n}" for n in spec.notes] + [""]
        cols = [spec.id_col, spec.org_col, spec.date_col, *spec.names, spec.target]
        pd.DataFrame(columns=cols).to_csv(out_dir / f"{name}_template.csv", index=False)
    (ROOT.parents[1] / "docs" / "ml-data-contract.md").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )
    print("written docs/ml-data-contract.md and", sorted(p.name for p in out_dir.iterdir()))


if __name__ == "__main__":
    main()
